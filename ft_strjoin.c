#include "libft.h"

char	*ft_strjoin(char const *s1, char const *s2)
{
	size_t	s1_len;
	size_t	s2_len;
	size_t	total_len;
	char	*p;

	if (s1 == NULL || s2 == NULL)
		return (NULL);
	s1_len = ft_strlen(s1);
	s2_len = ft_strlen(s2);
	total_len = s1_len + s2_len + 1;
	p = malloc(total_len);
	if (!p)
		return (NULL);
	ft_strlcpy(p, s1, s1_len + 1);
	ft_strlcpy(p + s1_len, s2, s2_len + 1);
	return (p);
}
